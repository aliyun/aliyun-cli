func extensionCommandParts(args []string, root string) []string {
	parts := []string{root}
	if len(args) == 0 || !strings.EqualFold(args[0], root) {
		return parts
	}
	paths := extensionCommandPaths[strings.ToLower(root)]
	path := ""
	for _, arg := range args[1:] {
		if strings.HasPrefix(arg, "-") {
			break
		}
		candidate := strings.ToLower(arg)
		if path != "" {
			candidate = path + " " + candidate
		}
		known := false
		for _, confirmed := range paths {
			if confirmed == candidate || strings.HasPrefix(confirmed, candidate+" ") {
				known = true
				break
			}
		}
		if !known {
			break
		}
		parts = append(parts, arg)
		path = candidate
	}
	return parts
}
